import React, { useMemo, useEffect, useRef } from 'react';
import { EditorContent, useEditor } from '@tiptap/react';
import StarterKit from '@tiptap/starter-kit';
import Placeholder from '@tiptap/extension-placeholder';
import { isHistoryTransaction } from '@tiptap/pm/history';
import { Instruction, AIHighlight, GlobalShortcuts } from '../lib/editor/extensions';
import { motion } from 'motion/react';
import { Book, MessageSquarePlus, Undo2, Redo2, Play, Sparkles, BookOpen, Compass } from 'lucide-react';
import { Novel } from '../types';
import { cn } from '../lib/utils';
import { useAutoCounters } from '../hooks/useAutoCounters';
import { GLOBAL_DEFAULTS } from '../constants';

interface EditorContainerProps {
  currentNovel: Novel | null;
  onEditorReady: (editor: any) => void;
  scrollContainerRef: React.RefObject<HTMLDivElement>;
  setIsCodexOpen: (open: boolean) => void;
  setIsPlotWorkbenchOpen?: (open: boolean) => void;
  hasPendingPlotProposal?: boolean;
  handleContinue: () => void;
  handleDryRunNovel: () => void;
  isGenerating: boolean;
  createNewNovel: () => void;
  debugMode?: boolean;
  updateNovelContent: (id: string, updates: Partial<Novel>, silent?: boolean) => void;
  incrementChars: (count: number) => void;
  lastContentRef: React.MutableRefObject<string>;
}

export const EditorContainer: React.FC<EditorContainerProps> = ({
  currentNovel,
  onEditorReady,
  scrollContainerRef,
  setIsCodexOpen,
  setIsPlotWorkbenchOpen,
  hasPendingPlotProposal,
  handleContinue,
  handleDryRunNovel,
  isGenerating,
  createNewNovel,
  debugMode,
  updateNovelContent,
  incrementChars,
  lastContentRef
}) => {
  const currentNovelRef = useRef(currentNovel);
  const updateNovelContentRef = useRef(updateNovelContent);
  const incrementCharsRef = useRef(incrementChars);
  const handleContinueRef = useRef(handleContinue);

  useEffect(() => {
    currentNovelRef.current = currentNovel;
    updateNovelContentRef.current = updateNovelContent;
    incrementCharsRef.current = incrementChars;
    handleContinueRef.current = handleContinue;
  }, [currentNovel, updateNovelContent, incrementChars, handleContinue]);

  const editor = useEditor({
    extensions: [
      StarterKit,
      Placeholder.configure({
        placeholder: 'Once upon a time...',
      }),
      Instruction,
      AIHighlight,
      GlobalShortcuts.configure({
        onGenerate: () => {
          handleContinueRef.current();
        },
      }),
    ],
    content: currentNovel?.content || '',
    editorProps: {
      attributes: {
        class: 'prose prose-invert max-w-none focus:outline-none p-6 sm:p-12 pb-64 sm:pb-64 text-lg sm:text-xl leading-relaxed font-serif text-zinc-300 whitespace-pre-wrap min-h-full',
      },
      handleKeyDown: (view, event) => {
        if ((event.ctrlKey || event.metaKey) && event.key === 'Enter') {
          handleContinueRef.current();
          return true;
        }
        return false;
      },
    },
    onUpdate: ({ editor, transaction }) => {
      // Safely ignore updates generated by the editor's initial content injection
      if (currentNovelRef.current?.content === undefined || loadedNovelIdRef.current !== currentNovelRef.current?.id) {
         return; 
      }
      
      if (transaction.getMeta('prevent-recursion')) return;

      if (transaction.docChanged) {
        // Delta calculation: emits positive diff for added text and negative diff for deleted text (floored at 0 in hooks).
        // Ignore Undo/Redo history transactions to prevent sudden bulk character restorations from falsely triggering auto-scans.
        if (!isHistoryTransaction(transaction)) {
          const diff = transaction.doc.content.size - transaction.before.content.size;
          if (diff !== 0) {
            incrementCharsRef.current(diff);
          }
        }

        // Only remove AI highlights when the user performs manual edits (excluding Undo/Redo)
        if (!transaction.getMeta('ai-generated') && !isHistoryTransaction(transaction)) {
          editor.chain()
            .setMeta('addToHistory', false)
            .setMeta('prevent-recursion', true)
            .command(({ tr }) => {
              const { size } = tr.doc.content;
              if (size > 0) {
                tr.removeMark(0, size, editor.schema.marks.aiHighlight);
              }
              return true;
            })
            .run();
        }
      }

      const latestNovel = currentNovelRef.current;
      if (latestNovel) {
        // Trigger auto-save without providing content immediately. 
        // useNovelContent will lazy-fetch the content via getEditorContent when it actually saves.
        updateNovelContentRef.current(latestNovel.id, { }, true);
      }
    },
  }, [currentNovel?.id]);

  useEffect(() => {
    if (editor) {
      onEditorReady(editor);
    }
  }, [editor, onEditorReady]);

  const loadedNovelIdRef = useRef<string | null>(null);

  // Sync editor with currentNovel ONLY when a new novel is loaded
  useEffect(() => {
    if (editor && currentNovel && currentNovel.content !== undefined) {
      if (loadedNovelIdRef.current !== currentNovel.id) {
        console.log("EditorContainer useEffect sync TRIGGERED! Loading novel:", currentNovel.id);
        
        try {
          editor.chain()
            .setContent(currentNovel.content || "", { emitUpdate: false })
            .setMeta('addToHistory', false)
            .run();
            
          lastContentRef.current = currentNovel.content || "";
          loadedNovelIdRef.current = currentNovel.id;
          
          setTimeout(() => {
            if (scrollContainerRef.current) {
              scrollContainerRef.current.scrollTop = scrollContainerRef.current.scrollHeight;
            }
            editor.commands.focus('end');
          }, 100);
        } catch (error) {
          console.error("Error setting editor content:", error);
        }
      }
    }
  }, [currentNovel?.id, currentNovel?.content, editor, lastContentRef, scrollContainerRef]);

  const undo = () => {
    if (editor) {
      editor.commands.undo();
    }
  };

  const redo = () => {
    if (editor) {
      editor.commands.redo();
    }
  };

  const insertInstruction = () => {
    if (editor) {
      (editor.commands as any).setInstruction();
    }
  };

  const { codexCount, plotCount } = useAutoCounters(currentNovel?.id);

  const isAutoCodex = currentNovel?.settings?.automation?.autoCodex ?? false;
  const isAutoPlot = currentNovel?.settings?.automation?.autoPlot ?? false;
  const codexTarget = currentNovel?.settings?.autoCodex?.triggerChars ?? currentNovel?.settings?.autoCodexTriggerChars ?? GLOBAL_DEFAULTS.autoCodex.triggerChars;
  const plotTarget = currentNovel?.settings?.plot?.triggerChars ?? GLOBAL_DEFAULTS.plot.triggerChars;

  const codexProgress = Math.min(100, Math.round((codexCount / (codexTarget || 1)) * 100));
  const plotProgress = Math.min(100, Math.round((plotCount / (plotTarget || 1)) * 100));

  const hasPendingProposals = useMemo(() => {
    if (!currentNovel?.loreEntries) return false;
    return currentNovel.loreEntries.some(entry => 
      entry.proposedContent || entry.isProposalOnly || entry.isPruningProposal
    );
  }, [currentNovel?.loreEntries]);

  return (
    <div className="flex-1 relative overflow-hidden">
      {currentNovel ? (
        <div className="absolute inset-0 flex flex-col overflow-hidden">
          {/* Editor Scroll Container */}
          <div 
            ref={scrollContainerRef}
            className="flex-1 overflow-y-auto custom-scrollbar relative z-10"
          >
            <div className="max-w-4xl mx-auto min-h-full relative px-6">
              <EditorContent editor={editor} />
            </div>
          </div>
          
          {/* Bottom Gradient for better readability behind floating buttons */}
          <div className="absolute bottom-0 left-0 right-0 h-28 sm:h-32 bg-gradient-to-t from-zinc-950 via-zinc-950/80 to-transparent pointer-events-none z-20" />
          
          {/* Floating Action Bar - Left Group (Codex & Plot with Sleek Progress Rings) */}
          <div className="absolute bottom-4 sm:bottom-8 left-3 sm:left-8 z-30 flex items-center gap-1.5 sm:gap-3">
            {/* Codex Button */}
            <div className="relative">
              <button 
                onClick={() => setIsCodexOpen(true)}
                className="relative flex items-center justify-center w-11 h-11 sm:w-14 sm:h-14 bg-zinc-900/90 backdrop-blur-md border border-zinc-800 text-zinc-400 hover:text-indigo-400 rounded-full transition-all active:scale-95 shadow-2xl shrink-0"
                title={`Open The Codex (${codexProgress}%)`}
              >
                <Book className="w-5 h-5 sm:w-6 sm:h-6" />
              </button>

              {/* SVG Circular Progress Ring for Auto-Codex */}
              {isAutoCodex && (
                <svg 
                  className="absolute -inset-0.5 w-[calc(100%+4px)] h-[calc(100%+4px)] -rotate-90 pointer-events-none" 
                  viewBox="0 0 100 100"
                >
                  <circle
                    cx="50"
                    cy="50"
                    r="46"
                    className="stroke-zinc-800/80"
                    strokeWidth="4"
                    fill="transparent"
                  />
                  <circle
                    cx="50"
                    cy="50"
                    r="46"
                    className="stroke-amber-500 transition-all duration-300"
                    strokeWidth="4"
                    fill="transparent"
                    strokeDasharray={289}
                    strokeDashoffset={289 - (289 * codexProgress) / 100}
                    strokeLinecap="round"
                  />
                </svg>
              )}

              {/* Proposal Badge - Promoted to topmost layer (z-20), maintaining original top-0 right-0 position */}
              {hasPendingProposals && (
                <span className="absolute top-0 right-0 w-2.5 h-2.5 sm:w-3.5 sm:h-3.5 bg-indigo-500 rounded-full border-2 border-zinc-900 animate-pulse z-20 pointer-events-none" />
              )}
            </div>

            {/* Plot Workbench Button */}
            {setIsPlotWorkbenchOpen && (
              <div className="relative">
                <button 
                  onClick={() => setIsPlotWorkbenchOpen(true)}
                  className="relative flex items-center justify-center w-11 h-11 sm:w-14 sm:h-14 bg-zinc-900/90 backdrop-blur-md border border-zinc-800 text-zinc-400 hover:text-purple-400 rounded-full transition-all active:scale-95 shadow-2xl shrink-0"
                  title={`Plot Workbench & Narrative Director (${plotProgress}%)`}
                >
                  <Compass className="w-5 h-5 sm:w-6 sm:h-6" />
                </button>

                {/* SVG Circular Progress Ring for Auto-Plot */}
                {isAutoPlot && (
                  <svg 
                    className="absolute -inset-0.5 w-[calc(100%+4px)] h-[calc(100%+4px)] -rotate-90 pointer-events-none" 
                    viewBox="0 0 100 100"
                  >
                    <circle
                      cx="50"
                      cy="50"
                      r="46"
                      className="stroke-zinc-800/80"
                      strokeWidth="4"
                      fill="transparent"
                    />
                    <circle
                      cx="50"
                      cy="50"
                      r="46"
                      className="stroke-purple-500 transition-all duration-300"
                      strokeWidth="4"
                      fill="transparent"
                      strokeDasharray={289}
                      strokeDashoffset={289 - (289 * plotProgress) / 100}
                      strokeLinecap="round"
                    />
                  </svg>
                )}

                {/* Proposal Badge - Promoted to topmost layer (z-20), maintaining original top-0 right-0 position */}
                {hasPendingPlotProposal && (
                  <span className="absolute top-0 right-0 w-2.5 h-2.5 sm:w-3.5 sm:h-3.5 bg-purple-500 rounded-full border-2 border-zinc-900 animate-pulse z-20 pointer-events-none" />
                )}
              </div>
            )}
          </div>

          {/* Floating Action Bar - Right Group (Instruction, Undo/Redo, Continue) */}
          <div className="absolute bottom-4 sm:bottom-8 right-3 sm:right-8 z-30 flex items-center gap-1.5 sm:gap-3">
            {/* Instruction Button */}
            <button 
              onClick={insertInstruction}
              className="flex items-center justify-center w-11 h-11 sm:w-14 sm:h-14 bg-zinc-900/90 backdrop-blur-md border border-zinc-800 text-zinc-400 hover:text-indigo-400 rounded-full transition-all active:scale-95 shadow-2xl shrink-0"
              title="Insert Editor Instruction"
            >
              <MessageSquarePlus className="w-5 h-5 sm:w-6 sm:h-6" />
            </button>

            {/* Undo/Redo Buttons for Mobile/Desktop */}
            <div className="flex items-center bg-zinc-900/90 backdrop-blur-md border border-zinc-800 rounded-full p-0.5 sm:p-1 shadow-2xl shrink-0">
              {debugMode && (
                <>
                  <button 
                    onClick={handleDryRunNovel}
                    className="p-2 sm:p-3 hover:bg-zinc-800 text-amber-500 rounded-full transition-all active:scale-90"
                    title="Debug Prompt (Dry-Run Context Builder)"
                  >
                    <Sparkles className="w-4 h-4 sm:w-5 sm:h-5" />
                  </button>
                  <div className="w-[1px] h-3 sm:h-4 bg-zinc-800 mx-0.5 sm:mx-1" />
                </>
              )}
              <button 
                onClick={undo}
                disabled={!editor?.can().undo()}
                className="p-2 sm:p-3 hover:bg-zinc-800 disabled:opacity-20 text-zinc-400 rounded-full transition-all active:scale-90"
                title="Undo (Ctrl+Z)"
              >
                <Undo2 className="w-4 h-4 sm:w-5 sm:h-5" />
              </button>
              <div className="w-[1px] h-3 sm:h-4 bg-zinc-800 mx-0.5 sm:mx-1" />
              <button 
                onClick={redo}
                disabled={!editor?.can().redo()}
                className="p-2 sm:p-3 hover:bg-zinc-800 disabled:opacity-20 text-zinc-400 rounded-full transition-all active:scale-90"
                title="Redo (Ctrl+Y)"
              >
                <Redo2 className="w-4 h-4 sm:w-5 sm:h-5" />
              </button>
            </div>

            <button 
              onClick={handleContinue}
              disabled={isGenerating}
              className="group flex items-center justify-center w-11 h-11 sm:w-14 sm:h-14 bg-indigo-600 hover:bg-indigo-500 disabled:bg-zinc-800 text-white rounded-full transition-all active:scale-95 shadow-2xl shadow-indigo-500/40 shrink-0"
              title="Continue Story (Ctrl+Enter)"
            >
              {isGenerating ? (
                <motion.div 
                  animate={{ rotate: 360 }} 
                  transition={{ duration: 1, repeat: Infinity, ease: "linear" }}
                >
                  <Sparkles className="w-5 h-5 sm:w-6 sm:h-6" />
                </motion.div>
              ) : (
                <div className="flex items-center gap-1.5 sm:gap-2">
                  <Play className="w-5 h-5 sm:w-6 sm:h-6 fill-current" />
                  <span className="max-w-0 overflow-hidden group-hover:max-w-xs transition-all duration-300 font-semibold whitespace-nowrap hidden sm:inline">
                    Continue
                  </span>
                </div>
              )}
            </button>
          </div>
        </div>
      ) : (
        <div className="flex-1 flex flex-col items-center justify-center text-zinc-600 space-y-4">
          <BookOpen className="w-16 h-16 opacity-20" />
          <p className="text-lg">Select a novel or create a new one to start writing.</p>
          <button 
            onClick={createNewNovel}
            className="px-6 py-2 bg-zinc-900 hover:bg-zinc-800 border border-zinc-800 rounded-xl text-zinc-400 transition-colors"
          >
            Create New Novel
          </button>
        </div>
      )}
    </div>
  );
};
